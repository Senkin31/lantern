def _e(v) -> str:
    return escape("" if v is None else str(v))


def render(ev: dict, tile_url: str, tile_attribution: str, images_credit: str, source_url: str,
           lang: str = "en") -> str:
    t = T.get(lang, T["en"])
    p, d = ev["place"], ev["deadline"]
    sf = d["snowfall"]
    if sf:
        snow_txt = f"{_e(t['snowfall'])} {_e(sf['start_riga'] or '?')} – {_e(sf['end_riga'] or t['snowing'])}"
    else:
        snow_txt = _e(t["unknown"])
    frames = "".join(
        f"""<figure><img src="{_e(f['frame_url'] or f['crop_url'])}" alt="{_e(t[f['label']])}">
<figcaption><b>{_e(t[f['label']])}</b><br>{_e(f['riga_time'])} ({_e(t['riga'])}) · {_e(f['timestamp'])} UTC<br>
{_e(f['hazard_class'])}, {_e(t['share'])} {f['blocked_share']:.0%}, {_e(t['conf'])} {f['confidence']:.2f}
· {_e(f['camera_id'])} / {_e(f['zone_id'])}</figcaption></figure>"""
        for f in ev["frames"]) or f"<p class=muted>{_e(t['no_frames'])}</p>"
    photos = "".join(
        f"""<figure><img src="{_e(r['photo_url'])}" alt="{_e(t['photo'])}"><figcaption>{_e(r['riga_time'])} ({_e(t['riga'])})
· {_e(t.get(r['passable'], r['passable']))}{' (' + _e(t.get('by_ai', 'AI')) + ')' if r.get('passable_by') == 'ai' else ''}{' · ' + _e(r['hazard']) if r['hazard'] else ''}
{'<br>&laquo;' + _e(r['comment']) + '&raquo;' if r['comment'] else ''}
{'<br>' + _e(t['reg']) + ' ' + _e(r['registration_no']) if r['registration_no'] else ''}</figcaption></figure>"""
        for r in ev["resident_photos"]) or f"<p class=muted>{_e(t['no_photos'])}</p>"
    times = "".join(f"<tr><th>{_e(t[k])}</th><td>{_e(v['riga_time'] or '—')}</td>"
                    f"<td class=muted>{_e(v['utc'] or '')}</td></tr>" for k, v in ev["times"].items())
    hist = "".join(f"<tr><td>{_e(h['riga_time'])}</td><td>{_e(h['from_status'] or '—')} → {_e(h['to_status'])}</td>"
                   f"<td>{_e(h['actor'])}</td><td>{_e(h['note'])}</td></tr>" for h in ev["history"])
    overdue = f'<span class="tag red">{_e(t["overdue"])}</span>' if ev["overdue"] else ""
    reopened = f" · reopened ×{ev['reopened_count']}" if ev["reopened_count"] else ""
    geo = json.dumps({"lat": p["lat"], "lon": p["lon"], "polygon": p["polygon"], "tile": tile_url,
                      "attr": tile_attribution}).replace("</", "<\\/")
